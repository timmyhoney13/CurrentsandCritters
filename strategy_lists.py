#!/usr/bin/env python3
"""What goes with what: every strategy, its cards, and the card that pays for it.

    python3 strategy_lists.py              # print it
    python3 strategy_lists.py --write      # also write STRATEGY_LISTS.txt

Everything here is DERIVED from the engine -- the card database, the card
family map, the payoff table, the anchor synergy lists and the skill
allowlist. Nothing is typed in twice. A card added to a plan, or a plan added
to the game, shows up here on the next run without anyone remembering to edit
a second copy, which is how the old hand-written list came to cover eleven
cards out of fifty-three.
"""
from __future__ import annotations

import argparse
import os
import sys
from collections import defaultdict
from typing import Dict, List

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
os.chdir(HERE)
import fish_game_all_in_one as fish
import reef_planner as rp


def build() -> str:
    db = fish.load_card_db()
    copies: Dict[str, int] = defaultdict(int)
    first: Dict[str, object] = {}
    for uid in sorted(db):
        c = db[uid]
        n = fish.card_name_lc(c)
        copies[n] += 1
        first.setdefault(n, c)

    by_family: Dict[str, List[str]] = defaultdict(list)
    oceans: List[str] = []
    neutral: List[str] = []
    for n, c in first.items():
        sp = fish.card_species_lc(c)
        if sp in ("ocean", "end game"):
            oceans.append(n)
            continue
        fam = fish._STRATEGY_OF_NAME.get(n) or fish._STRATEGY_OF_SPECIES.get(sp) or ""
        if fam:
            by_family[fam].append(n)
        else:
            neutral.append(n)

    out: List[str] = []
    w = out.append
    w("WHAT GOES WITH ALL THE STRATEGIES")
    w("=" * 78)
    w("")
    w(f"{len(db)} deck entries, {len(first)} different cards, "
      f"{len(rp.STRATEGY_FAMILIES)} plans a bot can commit to.")
    w("Generated by strategy_lists.py from the engine's own tables. Do not hand-edit.")
    w("")
    w("HOW TO READ A PLAN")
    w("  pays for it   the multiplier or count chart the plan scores through. Collect")
    w("                the family without one of these and you have collected nothing.")
    w("  cards         every card whose points belong to this plan.")
    w("  goes with     the anchor pairs: cards the engine floors as going together,")
    w("                because one of them says so in print.")
    w("  same ocean    pairs that have to land on the SAME ocean, not just the same")
    w("                board. Only four effects in the deck actually read the ocean.")
    w("  at            table sizes and skill tiers the plan is offered at.")
    w("")

    anchors: Dict[str, set] = {}
    for a, others in fish.PRIORITY_CARD_SYNERGY.items():
        anchors.setdefault(a, set()).update(others)
        for b in others:
            anchors.setdefault(b, set()).add(a)
    same_ocean: Dict[str, set] = {}
    for a, others in fish.PRIORITY_SAME_OCEAN_SYNERGY.items():
        same_ocean.setdefault(a, set()).update(others)
        for b in others:
            same_ocean.setdefault(b, set()).add(a)

    order = [f for f in rp.STRATEGY_FAMILIES if f not in rp.COMBO_PARENTS]
    order += [f for f in rp.STRATEGY_FAMILIES if f in rp.COMBO_PARENTS]
    for fam in order:
        disp = fish.STRATEGY_DISPLAY_NAMES.get(fam, fam)
        parents = rp.COMBO_PARENTS.get(fam)
        members = sorted(by_family.get(fam, []))
        if parents:
            members = sorted({n for p in parents for n in by_family.get(p, [])})
        pays = [p for p in fish.strategy_payoff_names(fam) if p in first]
        self_pay = fish.strategy_self_payoff_at(fam)
        prior = rp.FAMILY_PRIOR.get(fam)
        gate = rp.GATED_FAMILIES.get(fam)

        w("-" * 78)
        head = f"{disp.upper()}   [{fam}]"
        if parents:
            head += "   = " + " + ".join(fish.STRATEGY_DISPLAY_NAMES.get(p, p) for p in parents)
        w(head)
        skills = sorted(k for k, v in fish.STRATEGY_SKILL_ALLOWLIST.items() if fam in v)
        at = f"  at: {', '.join(skills) if skills else 'not offered to any skill tier'}"
        if fam == "invertebrates":
            at += f"; {fish.INVERTEBRATE_MIN_PLAYERS}+ players only"
        if gate:
            at += f"; only when the planner knob {gate} is on"
        w(at)
        if prior is not None:
            w(f"  measured worth to a planner that committed to it: {prior:+.1f} points"
              + ("  (no measurement yet)" if prior == 0.0 else ""))
        if pays:
            w(f"  pays for it: {', '.join(pays)}")
        else:
            w("  pays for it: nothing -- this plan has no multiplier of its own")
        if self_pay:
            w(f"  or pays off by itself once {self_pay} of its own cards are out")
        w("  cards:")
        for n in members:
            c = first[n]
            flag = " *" if n in pays else "  "
            txt = (c.text or "").replace("\n", " ")[:62]
            w(f"   {flag}{copies[n]:2d}x {n:24s} [{fish.card_species_lc(c):12s}] {txt}")
        pairs = [(n, sorted(anchors.get(n, ()))) for n in members if anchors.get(n)]
        if pairs:
            w("  goes with:")
            for n, others in pairs:
                w(f"      {n:24s} -> {', '.join(others)}")
        so = [(n, sorted(same_ocean.get(n, ()))) for n in members if same_ocean.get(n)]
        if so:
            w("  same ocean:")
            for n, others in so:
                w(f"      {n:24s} -> {', '.join(others)}")
        w("")

    w("-" * 78)
    w("CARDS IN NO PLAN")
    w("  Universal helpers: worth the same to every plan, so claiming them for one")
    w("  would be a lie. Their points are not counted towards any plan's total.")
    for n in sorted(neutral):
        c = first[n]
        w(f"     {copies[n]:2d}x {n:24s} [{fish.card_species_lc(c):12s}] "
          f"{(c.text or '').replace(chr(10), ' ')[:58]}")
    w("")
    w("-" * 78)
    w("OCEANS")
    w("  The ground every plan is built on, which is why Oceans is not a plan of its")
    w("  own: STRATEGY_SKILL_ALLOWLIST offers it at no skill tier, and the label")
    w("  exists only to name a finished board in the recap.")
    for n in sorted(oceans):
        c = first[n]
        w(f"     {copies[n]:2d}x {n:24s} {(c.text or '').replace(chr(10), ' ')[:66]}")
    w("")
    w("-" * 78)
    w("SPECIES THAT GO WITH SPECIES")
    for a, b in sorted(fish.PRIORITY_SPECIES_SYNERGY):
        w(f"     {a:14s} + {b}")
    w("")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true", help="write STRATEGY_LISTS.txt too")
    a = ap.parse_args()
    text = build()
    print(text)
    if a.write:
        with open(os.path.join(HERE, "STRATEGY_LISTS.txt"), "w", encoding="utf-8") as f:
            f.write(text + "\n")
        print("wrote STRATEGY_LISTS.txt")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
