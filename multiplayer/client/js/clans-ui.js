  // ---- Challenge rendering --------------------------------------------------
  // A clan challenge board is 12+ entries long, and as a stack of full-width
  // rows it read as a wall of text you scroll past: every line the same size,
  // the same colour, the one you could actually finish today indistinguishable
  // from the one nobody will touch. So each challenge is a CARD in a grid, with
  // the state carried by colour and a progress ring you can read at arm's
  // length: blue = under way, amber = nearly there, green = done. The ones you
  // are closest to finishing come first, done ones settle at the bottom.
  function challengeStatus(ch) {
    const target = Math.max(1, Number(ch.target || 1));
    const progress = Math.min(Number(ch.progress || 0), target);
    const pct = Math.min(100, Math.round(100 * progress / target));
    return { target, progress, pct,
             done: !!ch.done,
             near: !ch.done && pct >= 60,
             started: !ch.done && progress > 0 };
  }

  // Closest to done first, finished ones last: the board leads with what is
  // actually within reach this week.
  function challengeSort(list) {
    return (list || []).slice().sort((a, b) => {
      const A = challengeStatus(a), B = challengeStatus(b);
      if (A.done !== B.done) return A.done ? 1 : -1;
      return B.pct - A.pct;
    });
  }

  function challengeCard(ch) {
    const st = challengeStatus(ch);
    const left = countdownParts(ch.ends_ts || 0);
    const contribs = (ch.contributors || []).filter(x => x.points > 0);
    // "3d 4h left" for a week, "12d left" for a season: hours are noise on a
    // three-month clock.
    const clock = ch.ends_ts ? (left.d >= 14 ? `${left.d}d left` : `${left.d}d ${left.h}h left`) : "";
    const ring = st.done ? "#2e9e5b" : st.near ? "#f0930f" : "#2e8fe0";
    const cd = el("div", "ccC-chcard" + (st.done ? " done" : st.near ? " near" : st.started ? " go" : ""));
    cd.innerHTML = `
      <div class="hd">
        <div class="ccC-ring" style="--pct:${st.pct};--ring:${ring};"><i>${st.done ? "✓" : st.pct + "%"}</i></div>
        <div class="nm">${esc(ch.name)}
          <div class="ds">${esc(ch.desc || "")}</div>
        </div>
      </div>
      <div class="ds"><b style="color:${ring};">${st.progress}</b> / ${st.target}${clock ? " · ⏳ " + clock : ""}</div>
      <div class="ft">
        <span class="ccC-chip${st.done ? " gold" : ""}">+${esc(String(ch.clan_points))} pts</span>
        <span class="ccC-chip">+${ch.member_xp} XP</span>
        ${ch.min_contribution ? `<span class="ccC-chip" title="Your own contribution needed to share in the XP">needs ${ch.min_contribution}+ yours</span>` : ""}
      </div>
      ${contribs.length
        ? `<div class="who">` + contribs.slice(0, 6).map(x =>
            `<span class="ccC-chip${x.qualifies ? " gold" : ""}">${esc(x.name)} ${x.points}</span>`).join("")
          + (contribs.length > 6 ? `<span class="ccC-chip">+${contribs.length - 6} more</span>` : "")
          + `</div>`
        : ""}`;
    return cd;
  }

  // The board: a headline that says where the clan stands, filter pills, and
  // the grid. `opts.limit` shows only the first N (the Overview dashboard),
  // with a button through to the full tab.
  function challengeBoard(title, rows, emptyText, opts) {
    opts = opts || {};
    const list = challengeSort(rows);
    const done = list.filter(x => x.done);
    const points = list.reduce((n, ch) => n + (ch.done ? Number(ch.clan_points || 0) : 0), 0);
    const possible = list.reduce((n, ch) => n + Number(ch.clan_points || 0), 0);
    const sec = el("div", "ccC-sec");
    const head = el("div", "ccC-sec-h", title);
    sec.appendChild(head);
    if (!list.length) {
      const b = el("div", "ccC-sec-b");
      b.innerHTML = `<div class="ccC-empty" style="padding:8px;">${esc(emptyText || "Nothing here yet.")}</div>`;
      sec.appendChild(b);
      return sec;
    }

    // Headline: how far through the board this clan is, in one line.
    const sum = el("div", "ccC-chsum");
    const pct = Math.round(100 * done.length / list.length);
    const ends = list[0] && list[0].ends_ts ? countdownParts(list[0].ends_ts) : null;
    sum.innerHTML = `
      <div><div class="big">${done.length}<span style="font-size:13px;color:#7a9db8;">/${list.length}</span></div>
        <div class="lab">complete</div></div>
      <div><div class="big">${points}<span style="font-size:13px;color:#7a9db8;">/${possible}</span></div>
        <div class="lab">clan points banked</div></div>
      <div class="bar"><div class="ccC-goalbar" style="margin-top:0;"><i style="width:${pct}%"></i></div>
        <div class="lab" style="margin-top:5px;">${ends
          ? (opts.endsLabel || "resets in") + ` ${ends.d}d ${ends.h}h`
          : "in progress"}</div></div>`;
    sec.appendChild(sum);

    const grid = el("div", "ccC-chgrid");
    let filter = "all";
    function paint() {
      grid.innerHTML = "";
      let show = list;
      if (filter === "todo") show = list.filter(x => !x.done);
      else if (filter === "done") show = done;
      if (opts.limit) show = show.slice(0, opts.limit);
      if (!show.length) {
        grid.innerHTML = `<div class="ccC-empty" style="padding:8px;">${
          filter === "done" ? "Nothing finished yet this week: pick one and go 🐙"
                            : "Every single one is done. Outstanding. 🏆"}</div>`;
        return;
      }
      show.forEach(ch => grid.appendChild(challengeCard(ch)));
    }

    // Filters earn their place once there is something in both buckets.
    if (!opts.limit && done.length && done.length < list.length) {
      const pills = el("div", "ccC-chfilter");
      [["all", "All " + list.length], ["todo", "Still to do " + (list.length - done.length)],
       ["done", "Done " + done.length]].forEach(([id, label]) => {
        const p = el("button", "ccC-chpill" + (filter === id ? " on" : ""), label);
        p.addEventListener("click", () => {
          filter = id;
          Array.prototype.forEach.call(pills.children, (x, i) =>
            x.classList.toggle("on", ["all", "todo", "done"][i] === id));
          paint();
        });
        pills.appendChild(p);
      });
      sec.appendChild(pills);
    }
    paint();
    sec.appendChild(grid);
    if (opts.limit && list.length > opts.limit) {
      const more = el("div", "ccC-chmore");
      const b = el("button", "ccC-btn tiny", `See all ${list.length} challenges →`);
      b.addEventListener("click", () => { C.clanTab = "challenges"; render(); });
      more.appendChild(b);
      sec.appendChild(more);
    }
    return sec;
  }

