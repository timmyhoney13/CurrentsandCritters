  function openClan(clanId) {
    C.viewingClanId = clanId;
    C.clanTab = "overview";
    // Opening YOUR OWN clan needs no request: /home already returned the exact
    // same profile payload (my_clan_full is _clan_profile), fetched moments ago
    // by the refresh that drew the screen you just clicked on. Seeding it here
    // is what turns "Loading clan…" into an instant open. Rank and record are
    // the only two fields /get adds on top, and the leaderboard row beside it
    // carries both. Any other clan still loads normally.
    const mine = (C.home && C.home.my_clan_full) || null;
    if (mine && mine.id === clanId) {
      C.clan = mine;
      const row = (C.home && C.home.my_clan) || null;
      if (row) { C.clan.rank = row.rank; C.clan.record = row.record; }
    } else {
      C.clan = null;
    }
    nav("clan");
  }

  // ── Joining, in one press ───────────────────────────────────────────────────
  // Every "how do I join?" answer comes down to one button, so there is exactly
  // one implementation of it: the open-clans list on the home screen and every
  // row in Browse both call this. A public clan is one press away from being
  // yours; a request-only clan is one press away from having asked.
  //
  // The button is taken out of service while the request is in flight: joining
  // is a transaction on the server and a double press is a second one.
  async function joinFromRow(cl, btn) {
    // A password clan asks one question first, then joins exactly like a public
    // one. The password is only ever sent to the server, nothing on this side
    // knows or checks it.
    if (cl.privacy === "password") { passwordJoinModal(cl, btn); return; }
    const wasText = btn.textContent;
    btn.disabled = true;
    btn.textContent = cl.privacy === "public" ? "Joining…" : "Asking…";
    const res = await post(cl.privacy === "public" ? "join" : "request", { clan_id: cl.id });
    if (res && res.ok) {
      if (cl.privacy === "public") {
        toast("Welcome to " + cl.name + "! 🛡️", "success");
        C.home = null; C.openClans = null;
        await refreshHome(true);
        openClan(cl.id);
      } else {
        toast("Join request sent to " + cl.name + " ✉️", "success");
        btn.textContent = "Requested";
      }
      return;
    }
    toast(errMsg(res && res.error), "error");
    btn.disabled = false;
    btn.textContent = wasText;
  }

