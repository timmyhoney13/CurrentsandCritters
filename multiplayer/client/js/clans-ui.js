  // ---- Clan chat ------------------------------------------------------------
  // ONE chat implementation, mounted in two places: the Chat tab (full height)
  // and the Overview dashboard (compact). Both share the message store below,
  // so switching between them never re-downloads the conversation and never
  // shows two different versions of it.
  //
  // The store is keyed BY MESSAGE ID, and that is the fix for "the clan chat
  // doesn't work". `ts` is only accurate to the second, so the old exclusive
  // `ts > since` cursor silently ate anything written in the same second as
  // the newest message already held: a clanmate replying at the same moment,
  // or a reply landing in the same second as your own line. The cursor never
  // moves back, so those messages were gone until a page reload. Now the
  // server re-serves that whole second (inclusive) and the ids decide what is
  // actually new.
  function stopChatPoll() {
    if (C.chatTimer) { clearInterval(C.chatTimer); C.chatTimer = null; }
  }

  // Wipe the conversation itself (leaving the clan, switching account).
  function resetChat() {
    stopChatPoll();
    C.chatSince = 0; C.chatMsgs = []; C.chatIds = Object.create(null);
  }

  // Fold a batch of server rows into the store. Returns the ones that were new.
  function mergeChat(rows) {
    const fresh = [];
    (rows || []).forEach(m => {
      if (!m || !m.id || C.chatIds[m.id]) return;
      C.chatIds[m.id] = true;
      C.chatMsgs.push(m);
      fresh.push(m);
      const ts = Number(m.ts || 0);
      if (ts > C.chatSince) C.chatSince = ts;
    });
    if (!fresh.length) return fresh;
    C.chatMsgs.sort((a, b) => (Number(a.ts || 0) - Number(b.ts || 0))
                              || String(a.id).localeCompare(String(b.id)));
    // Keep the store bounded, and keep the id set honest about what is in it,
    // or a trimmed message could never arrive again.
    if (C.chatMsgs.length > 160) {
      C.chatMsgs.splice(0, C.chatMsgs.length - 160).forEach(m => { delete C.chatIds[m.id]; });
    }
    return fresh;
  }

  // One message bubble. `my` may be null (read-only render).
