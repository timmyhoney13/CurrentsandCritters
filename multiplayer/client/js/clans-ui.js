  // ---- Challenge rendering (shared by Overview, the Challenges tab, and the
  // in-game challenge sheet, so one row format is the only one to keep right).
  function challengeRow(ch) {
    const target = Math.max(1, Number(ch.target || 1));
    const progress = Math.min(Number(ch.progress || 0), target);
    const pct = Math.min(100, Math.round(100 * progress / target));
    const left = countdownParts(ch.ends_ts || 0);
    const contribs = (ch.contributors || []).filter(x => x.points > 0);
    const row = el("div", "ccC-chall");
    // "3d 4h left" for a week, "12d left" for a season: hours are noise on a
    // three-month clock.
    const clock = ch.ends_ts ? (left.d >= 14 ? `${left.d}d left` : `${left.d}d ${left.h}h left`) : "";
    row.innerHTML = `<div style="display:flex;justify-content:space-between;gap:8px;">
        <b>${ch.done ? "✅ " : ""}${esc(ch.name)}</b>
        <span class="ccC-chip${ch.done ? " gold" : ""}">+${esc(String(ch.clan_points))} pts · +${ch.member_xp} XP</span></div>
      <div class="ccC-hint">${esc(ch.desc || "")}</div>
      <div class="ccC-goalbar"><i style="width:${pct}%"></i></div>
      <div class="ccC-hint">${progress}/${target}${clock ? " · ⏳ " + clock : ""}
        · needs ${ch.min_contribution}+ of your own points for the XP</div>
      ${contribs.length
        ? `<div class="ccC-hint" style="margin-top:3px;">👥 Contributed: ` + contribs.map(x =>
            `<span class="ccC-chip${x.qualifies ? " gold" : ""}">${esc(x.name)} ${x.points}</span>`).join(" ") + "</div>"
        : ""}`;
    return row;
  }

  function challengeSection(title, rows, emptyText) {
    const sec = el("div", "ccC-sec");
    const list = rows || [];
    const doneCount = list.filter(x => x.done).length;
    sec.appendChild(el("div", "ccC-sec-h",
      `${title}<span class="ccC-chip${doneCount && doneCount === list.length ? " gold" : ""}">${doneCount}/${list.length} done</span>`));
    const b = el("div", "ccC-sec-b");
    if (!list.length) {
      b.innerHTML = `<div class="ccC-empty" style="padding:8px;">${esc(emptyText || "Nothing here yet.")}</div>`;
    } else {
      list.forEach(ch => b.appendChild(challengeRow(ch)));
    }
    sec.appendChild(b);
    return sec;
  }

