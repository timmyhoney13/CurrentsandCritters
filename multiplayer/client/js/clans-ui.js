  function seasonNumFromSid(sid) {
    const m = /^(\d{4})-Q([1-4])$/.exec(String(sid || ""));
    if (!m) return "?";
    return Math.max(1, (Number(m[1]) - 2026) * 4 + (Number(m[2]) - 3) + 1);
  }

